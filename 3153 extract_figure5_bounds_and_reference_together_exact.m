function T = makeCurveTableExact(data_in)
    point_id = (1:size(data_in,1)).';
    east_m   = data_in(:,1);
    north_m  = data_in(:,2);
    z_m      = nan(size(data_in,1),1);
    s_m      = data_in(:,3);

    T = table(point_id, east_m, north_m, z_m, s_m);
end

function XY = eastNorthToPix(EN, W, H, east_min, east_max, north_min, north_max)
    east = EN(:,1);
    north = EN(:,2);

    x = 1 + (east - east_min)   ./ (east_max - east_min)   .* (W-1);
    y = 1 + (north_max - north) ./ (north_max - north_min) .* (H-1);

    XY = [x, y];
end
